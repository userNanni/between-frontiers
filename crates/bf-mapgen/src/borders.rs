//! The length of the border between every two neighbouring states, from `provinces.png` and
//! `provinces.ron`: the width of a front segment (`assets/map/borders.ron`). Run with
//! `cargo run -p bf-mapgen --release -- borders`; needs no raw source.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use bf_sim::scenario::MapFile;
use bf_sim::war::{BordersFile, StateBorder};

use crate::projection::Frame;
use crate::terrain::read_png16;

/// Km of a degree of latitude, and of longitude at the equator.
const KM_PER_DEGREE: f64 = 111.32;

/// The border of every pair of states, km. The pixel steps are counted as they run, with no
/// correction for their staircase: the map's borders are already simplified, and the steps
/// bring them back near the true lengths (Hungary–Romania 443 km against 432, France–Germany
/// 305 against about 290 in 1925). Each pixel edge between two states counts its
/// length on the ground, a vertical edge the height of its row and a horizontal edge the width
/// of a pixel at its latitude.
pub fn borders(frame: &Frame, land: &[u16], state_of_province: &[u16]) -> Vec<StateBorder> {
    let (w, h) = (frame.width as usize, frame.height as usize);
    let lat = |y: f64| frame.to_lon_lat(0.0, y).1;
    // Height of row y and width of a pixel on the line between rows y and y + 1, km.
    let row_km: Vec<f64> = (0..h)
        .map(|y| (lat(y as f64) - lat(y as f64 + 1.0)).abs() * KM_PER_DEGREE)
        .collect();
    let col_km: Vec<f64> = (0..h)
        .map(|y| {
            360.0 / f64::from(frame.width) * KM_PER_DEGREE * lat(y as f64 + 1.0).to_radians().cos()
        })
        .collect();
    let mut pairs: BTreeMap<(u16, u16), f64> = BTreeMap::new();
    for i in 0..w * h {
        let s = state_of_province[land[i] as usize];
        if s == 0 {
            continue;
        }
        let (x, y) = (i % w, i / w);
        let right = if x + 1 == w { i + 1 - w } else { i + 1 };
        let below = (i + w < w * h).then_some(i + w);
        for (j, km) in [(Some(right), row_km[y]), (below, col_km[y])] {
            let Some(j) = j else { continue };
            let t = state_of_province[land[j] as usize];
            if t == 0 || t == s {
                continue;
            }
            *pairs.entry((s.min(t), s.max(t))).or_default() += km;
        }
    }
    pairs
        .into_iter()
        .map(|((a, b), km)| StateBorder {
            a,
            b,
            km: km.round().max(1.0) as u32,
        })
        .collect()
}

pub fn run(root: &Path, frame: &Frame) -> Result<(), String> {
    let (w, h, land) = read_png16(&root.join("assets/map/provinces.png"))?;
    if (w, h) != (frame.width, frame.height) {
        return Err(format!(
            "provinces.png is {w}x{h}, expected {}x{}",
            frame.width, frame.height
        ));
    }
    let map_path = root.join("assets/map/provinces.ron");
    let map: MapFile = ron::from_str(
        &fs::read_to_string(&map_path).map_err(|e| format!("{}: {e}", map_path.display()))?,
    )
    .map_err(|e| format!("{}: {e}", map_path.display()))?;
    let state_of_province: Vec<u16> = std::iter::once(0)
        .chain(map.provinces.iter().map(|p| p.state))
        .collect();
    let file = BordersFile {
        borders: borders(frame, &land, &state_of_province),
    };
    let config = ron::ser::PrettyConfig::new().depth_limit(2);
    let body = ron::ser::to_string_pretty(&file, config).map_err(|e| e.to_string())?;
    let text = format!(
        "// Generated by `cargo run -p bf-mapgen --release -- borders`; do not edit by hand.\n\
         // Format: bf_sim::war::BordersFile: the km of border between neighbouring states, the\n\
         // width of a front segment (docs/war.pt-BR.md, \"Ritmo da frente\").\n{body}\n"
    );
    let _: BordersFile =
        ron::from_str(&text).map_err(|e| format!("borders.ron does not read back: {e}"))?;
    fs::write(root.join("assets/map/borders.ron"), text).map_err(|e| e.to_string())?;
    let total: u64 = file.borders.iter().map(|b| u64::from(b.km)).sum();
    println!("{} borders between states, {total} km", file.borders.len());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Two states side by side on the equator: their border is the height of the map's rows.
    #[test]
    fn a_border_counts_its_km() {
        let frame = Frame::new(360, 10.0, -10.0);
        let (w, h) = (frame.width as usize, frame.height as usize);
        let land: Vec<u16> = (0..w * h)
            .map(|i| if i % w < w / 2 { 1 } else { 2 })
            .collect();
        let b = borders(&frame, &land, &[0, 1, 2]);
        assert_eq!(b.len(), 1);
        // Two borders (the middle and the date line), each some 20 degrees of latitude.
        let expected = 2.0 * 20.0 * KM_PER_DEGREE;
        assert!(
            (f64::from(b[0].km) - expected).abs() / expected < 0.05,
            "{:?}",
            b
        );
    }
}
