"""Builds data/scenario/1925/industry.ron from tools/initial/industry.csv.

Run from the repository root:

    python3 -I tools/initial/industry.py

Prints world totals and the largest producers (also written to tools/initial/industry_check.md).
"""

import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from common import ROOT, read_countries  # noqa: E402

OUT = os.path.join(ROOT, "data/scenario/1925/industry.ron")
CHECK = os.path.join(HERE, "industry_check.md")
UNITS = [
    ("steel", "kt crude steel"),
    ("pig_iron", "kt"),
    ("cement", "kt"),
    ("textiles", "kt fibre spun and woven by mills (cotton, wool, jute, flax, silk, rayon)"),
    ("paper", "kt paper and board"),
    ("electricity", "GWh generated"),
    ("fuel", "kt refined petroleum products"),
    ("chemicals", "kt sulfuric acid as H2SO4 (proxy)"),
    ("fertilizer", "kt nutrients (N + P2O5 + K2O)"),
    ("explosives", "kt commercial explosives"),
    ("aluminium", "kt primary"),
    ("copper", "kt refined"),
    ("base_metals", "kt refined lead + zinc + tin"),
    ("automobiles", "thousand vehicles (cars and trucks, assembly from kits excluded)"),
    ("ships", "thousand GRT launched"),
    ("railways_km", "km of public railway route"),
    ("merchant_fleet_grt", "thousand GRT (steam and motor, 100 GRT and over)"),
    ("telephones", "thousand telephone sets"),
]
# Reference world totals for 1925 (see INITIAL.md).
REFERENCE = {
    "steel": "≈ 90 000", "cement": "≈ 60 000–70 000", "electricity": "≈ 180 000–200 000",
    "aluminium": "≈ 180–200", "automobiles": "≈ 4 700 (EUA ≈ 4 300)", "pig_iron": "≈ 76 000",
    "ships": "≈ 2 200 (Lloyd's)", "merchant_fleet_grt": "≈ 62 000–64 000 (Lloyd's)",
    "telephones": "≈ 26 000–27 000 (AT&T, 1/1/1926)", "fertilizer": "≈ 5 000–6 000",
    "copper": "≈ 1 400–1 600", "base_metals": "≈ 2 900–3 100",
    "railways_km": "≈ 1 200 000", "fuel": "≈ 140 000 (petróleo bruto: ≈ 146 000)",
}


def fmt(v):
    v = float(v)
    return f"{v:.1f}" if v != int(v) else f"{int(v)}.0"


def main():
    countries = read_countries()
    rows = list(csv.DictReader(r for r in open(os.path.join(HERE, "industry.csv"), encoding="utf-8")
                               if not r.startswith("#")))
    keys = [k for k, _ in UNITS]
    tags = [r["country"] for r in rows]
    assert len(tags) == len(set(tags)), "duplicate country"
    missing = set(countries) - set(tags)
    assert not missing, f"no industry row: {sorted(missing)}"
    lines = [
        "// Between Frontiers: industrial output in 1925 and infrastructure stocks per country",
        "// (owners include their colonies). Format: bf_sim::initial::IndustryFile. Generated by",
        "// tools/initial/industry.py from tools/initial/industry.csv; sources, estimates and",
        "// doubts in INITIAL.md. Licence: CC BY-SA 4.0.",
        "(",
        "    units: [",
    ]
    lines += [f'        ("{k}", "{u}"),' for k, u in UNITS]
    lines += ["    ],", "    countries: ["]
    order = {t: i for i, t in enumerate(countries)}
    for r in sorted(rows, key=lambda r: order[r["country"]]):
        assert r["country"] in countries, r["country"]
        est = r["est"]
        assert est == "all" or all(e in keys for e in est.split(";") if e), (r["country"], est)
        out = ", ".join(f'("{k}", {fmt(r[k])})' for k in keys)
        src = r["note"] + ("; every value is an estimate" if est == "all" else
                           (f"; estimates: {est.replace(';', ', ')}" if est else ""))
        src = src.replace('"', "'")
        lines.append(f'        (country: "{r["country"]}", output: [{out}], source: "{src}"),')
    lines += ["    ],", ")", ""]
    open(OUT, "w", encoding="utf-8").write("\n".join(lines))

    rep = ["# Indústria de 1925: totais mundiais e maiores produtores", "",
           "Gerado por `tools/initial/industry.py`. Não editar à mão.", "",
           "| Grandeza | Unidade | Total do arquivo | Referência | Maiores (país: valor) |", "|---|---|---|---|---|"]
    for k, u in UNITS:
        vals = sorted(((float(r[k]), r["country"]) for r in rows), reverse=True)
        tot = sum(v for v, _ in vals)
        top = ", ".join(f"{t} {v:,.0f}" if v >= 100 else f"{t} {v:g}" for v, t in vals[:10] if v > 0)
        rep.append(f"| {k} | {u} | {tot:,.1f} | {REFERENCE.get(k, '')} | {top} |")
    open(CHECK, "w", encoding="utf-8").write("\n".join(rep) + "\n")
    print("\n".join(rep))


if __name__ == "__main__":
    main()
